/**
 * Retrieval eval for /ask.
 *
 *   npx tsx scripts/ask-eval.ts report     measure against the live archive
 *   npx tsx scripts/ask-eval.ts snapshot   freeze the candidate pool for CI
 *   npx tsx scripts/ask-eval.ts replay     measure against the frozen snapshot
 *
 * `report` is the honest number: it runs the same path the API route runs, from
 * `resolveQuestion` through the candidate queries and `rankCandidates`, so it
 * measures what a reader gets. `replay` measures the same ranking decisions
 * against a pool captured earlier, which is what makes the suite in
 * `src/__tests__/askRetrieval.test.ts` runnable in CI without a database.
 *
 * The two are not interchangeable and the difference matters. A change to the
 * candidate SQL narrows the pool and `replay` will not see it; a change to the
 * weights or the caps moves both. Re-snapshot whenever `askSearch.ts` touches
 * its queries, and read `report` before believing a green suite.
 */

import dotenv from 'dotenv'
import fs from 'node:fs'
import path from 'node:path'

import type {
  AskMatchMode,
} from '@/lib/askQuery'
import type { ConversationState } from '@/lib/askConversation'
import type { CollectionTotal, SearchCandidate } from '@/lib/askSearch'
import type { GoldenCase, Observation } from '@/lib/askEval'

const SNAPSHOT_PATH = path.resolve(process.cwd(), 'src/__tests__/fixtures/askSnapshot.json')

/**
 * Rows kept per collection in the frozen pool.
 *
 * The ranking caps are 6 for documents and 3 or 2 for everything else, so no
 * more than six rows from any collection can reach the answer. Eight leaves
 * headroom for a cap being raised without invalidating the snapshot, while
 * keeping the file small enough to read.
 */
const KEEP_PER_COLLECTION = 8

/**
 * Longest field text kept in the snapshot.
 *
 * Only the eight curated documents carry prose, and their bodies are the bulk of
 * the file. Truncating can only remove a term a record would otherwise have
 * matched, so a replay scores conservatively: the CI numbers are a floor, and a
 * regression that only shows up live is still worth chasing.
 */
const KEEP_FIELD_CHARS = 4000

interface SnapshotCase {
  id: string
  terms: string[]
  context: string[]
  candidates: SnapshotCandidate[]
  totals: CollectionTotal[]
}

/**
 * A candidate reduced to what ranking actually reads.
 *
 * `excerpt` and `body` are dropped: every field `rankCandidates` scores is
 * already in `fields`, so keeping them doubles the fixture for nothing, and the
 * prose in a candidate is not what a retrieval change moves. Regenerate the
 * snapshot if an eval ever needs to assert on them.
 */
type SnapshotCandidate = Omit<SearchCandidate, 'excerpt' | 'body' | 'hasTranscript' | 'role'>

interface Snapshot {
  /** Prose, so a fixture generated by an older corpus is never silently reused. */
  note: string
  generatedAt: string
  caseCount: number
  cases: SnapshotCase[]
}

/**
 * The archive-facing modules, loaded once `dotenv` has run.
 *
 * `src/lib/prisma.ts` builds its Neon adapter at module load, and an import
 * declaration is evaluated before the `dotenv.config()` above it — so importing
 * it statically reaches the database with no connection string and fails with
 * `host: localhost`. Type-only imports above are erased and cost nothing.
 */
interface Archive {
  golden: GoldenCase[]
  resolveQuestion: (question: string) => ConversationState
  collectCandidates: (
    terms: string[],
  ) => Promise<{ candidates: SearchCandidate[]; totals: CollectionTotal[] }>
  rankCandidates: (
    candidates: SearchCandidate[],
    terms: string[],
    totals: CollectionTotal[],
    context: string[],
  ) => { mode: AskMatchMode; results: Array<{ candidate: SearchCandidate }> }
  scoreRetrieval: typeof import('@/lib/askEval')['scoreRetrieval']
  formatReport: typeof import('@/lib/askEval')['formatReport']
  sourceKey: (source: { collection: string; title: string }) => string
}

async function loadArchive(): Promise<Archive> {
  dotenv.config({ path: path.resolve(process.cwd(), '.env') })
  const conversation = await import('@/lib/askConversation')
  const search = await import('@/lib/askSearch')
  const evaluation = await import('@/lib/askEval')
  const fixtures = await import('@/__tests__/fixtures/askGolden')
  return {
    golden: fixtures.ASK_GOLDEN,
    resolveQuestion: conversation.resolveQuestion,
    collectCandidates: search.collectCandidates,
    rankCandidates: search.rankCandidates as Archive['rankCandidates'],
    scoreRetrieval: evaluation.scoreRetrieval,
    formatReport: evaluation.formatReport,
    sourceKey: evaluation.sourceKey,
  }
}

function trimForSnapshot(candidates: SearchCandidate[]): SnapshotCandidate[] {
  const perCollection: Record<string, number> = {}
  const kept: SnapshotCandidate[] = []
  for (const candidate of candidates) {
    const seen = (perCollection[candidate.collection] = (perCollection[candidate.collection] ?? 0) + 1)
    if (seen > KEEP_PER_COLLECTION) continue
    const { excerpt, body, hasTranscript, role, ...read } = candidate
    void excerpt
    void body
    void hasTranscript
    void role
    kept.push({
      ...read,
      fields: candidate.fields.map(field => ({ ...field, text: field.text.slice(0, KEEP_FIELD_CHARS) })),
    })
  }
  return kept
}

/** One pass over the archive: the same work `/api/ask` does, minus the prose. */
async function observeLive(archive: Archive): Promise<{
  observations: Map<string, Observation>
  snapshot: Snapshot
  latency: number[]
}> {
  const observations = new Map<string, Observation>()
  const cases: SnapshotCase[] = []
  const latency: number[] = []

  for (const testCase of archive.golden) {
    const resolved = archive.resolveQuestion(testCase.question)
    const started = Date.now()
    const { candidates, totals } = await archive.collectCandidates(resolved.terms)
    const ranked = archive.rankCandidates(candidates, resolved.terms, totals, resolved.context)
    latency.push(Date.now() - started)

    observations.set(testCase.id, {
      id: testCase.id,
      keys: ranked.results.map(result => archive.sourceKey(result.candidate)),
      mode: ranked.mode,
    })
    cases.push({
      id: testCase.id,
      terms: resolved.terms,
      context: resolved.context,
      candidates: trimForSnapshot(candidates),
      totals,
    })
  }

  return {
    observations,
    latency,
    snapshot: {
      note:
        `Frozen candidate pools for ${archive.golden.length} golden questions. Regenerate with ` +
        `\`npx tsx scripts/ask-eval.ts snapshot\` after changing the candidate queries in askSearch.ts.`,
      generatedAt: new Date().toISOString(),
      caseCount: archive.golden.length,
      cases,
    },
  }
}

function readSnapshot(): Snapshot {
  if (!fs.existsSync(SNAPSHOT_PATH)) {
    throw new Error(
      `no snapshot at ${path.relative(process.cwd(), SNAPSHOT_PATH)} — run \`npx tsx scripts/ask-eval.ts snapshot\` first`,
    )
  }
  return JSON.parse(fs.readFileSync(SNAPSHOT_PATH, 'utf8')) as Snapshot
}

function replay(archive: Archive, snapshot: Snapshot): Map<string, Observation> {
  const observations = new Map<string, Observation>()
  for (const entry of snapshot.cases) {
    const ranked = archive.rankCandidates(entry.candidates, entry.terms, entry.totals, entry.context)
    observations.set(entry.id, {
      id: entry.id,
      keys: ranked.results.map(result => archive.sourceKey(result.candidate)),
      mode: ranked.mode,
    })
  }
  return observations
}

/** What each failing case returned, in rank order. */
function printKeys(archive: Archive, observations: Map<string, Observation>): void {
  const report = archive.scoreRetrieval(archive.golden, observations)
  for (const failure of report.failures) {
    console.log(`  ${failure.id}`)
    const keys = observations.get(failure.id)?.keys ?? []
    if (keys.length === 0) {
      console.log('    (nothing returned)')
      continue
    }
    keys.forEach((key, index) => console.log(`    ${String(index + 1).padStart(2)}. ${key}`))
  }
  console.log('')
}

async function main(): Promise<void> {
  const command = process.argv[2] ?? 'report'
  /** `--keys` prints what every failing case actually returned, which is the
   *  difference between "the fixture names the wrong record" and "the search
   *  cannot find the right one". */
  const showKeys = process.argv.includes('--keys')
  const archive = await loadArchive()

  if (command === 'replay') {
    const snapshot = readSnapshot()
    const missing = archive.golden.filter(c => !snapshot.cases.some(entry => entry.id === c.id))
    const extra = snapshot.cases.filter(entry => !archive.golden.some(c => c.id === entry.id))
    if (missing.length > 0 || extra.length > 0) {
      console.warn(
        `[ask-eval] snapshot is out of step with the golden set: ${missing.length} missing, ${extra.length} unknown` +
          `${missing.length > 0 ? ` (${missing.map(c => c.id).join(', ')})` : ''}` +
          `${extra.length > 0 ? ` (${extra.map(c => c.id).join(', ')})` : ''}` +
          '\n[ask-eval] those cases are reported as failures. Re-snapshot.',
      )
    }
    const observations = replay(archive, snapshot)
    console.log(archive.formatReport(archive.scoreRetrieval(archive.golden, observations)))
    if (showKeys) printKeys(archive, observations)
    return
  }

  const { observations, snapshot, latency } = await observeLive(archive)
  console.log(archive.formatReport(archive.scoreRetrieval(archive.golden, observations)))
  if (showKeys) printKeys(archive, observations)

  const sorted = [...latency].sort((a, b) => a - b)
  const at = (q: number) => sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * q))]
  console.log(
    `  latency        p50 ${at(0.5)}ms · p90 ${at(0.9)}ms · max ${sorted[sorted.length - 1]}ms per question\n`,
  )

  if (command === 'snapshot') {
    // Compact: this file is generated, is read by nothing but the replay, and a
    // pretty-printed megabyte of scraped headlines makes an unreadable diff.
    fs.writeFileSync(SNAPSHOT_PATH, `${JSON.stringify(snapshot)}\n`)
    const kb = Math.round(fs.statSync(SNAPSHOT_PATH).size / 1024)
    console.log(`  wrote ${path.relative(process.cwd(), SNAPSHOT_PATH)} (${snapshot.cases.length} cases, ${kb}KB)`)
  }
}

main().catch(err => {
  console.error(err)
  process.exitCode = 1
})
